package change

import (
	"context"
	"regexp"
	"strings"
	"sync"
	"time"

	"github.com/opsmini/opsmini/internal/model"
)

// firewallSource snapshots the active rule set and reports semantic changes.
type firewallSource struct {
	cfg   *Config
	emit  func(Event)
	mu    sync.Mutex
	last  string
	tool  string
}

func newFirewallSource(cfg *Config, emit func(Event)) *firewallSource {
	return &firewallSource{cfg: cfg, emit: emit}
}

func (s *firewallSource) Name() string { return "firewall" }

func (s *firewallSource) Run(ctx context.Context) {
	interval := s.cfg.Firewall.PollInterval
	if interval <= 0 {
		interval = 5 * time.Minute
	}
	t := time.NewTicker(interval)
	defer t.Stop()
	s.poll(true)
	for {
		select {
		case <-ctx.Done():
			return
		case <-t.C:
			s.poll(false)
		}
	}
}

// snapshotRules returns the normalized active rule set and the tool used.
func snapshotRules() (rules, tool string) {
	type attempt struct {
		bin  string
		args []string
		name string
	}
	for _, a := range []attempt{
		{"/usr/sbin/iptables-save", nil, "iptables"},
		{"/usr/bin/iptables-save", nil, "iptables"},
		{"/usr/sbin/nft", []string{"list", "ruleset"}, "nftables"},
		{"/usr/bin/nft", []string{"list", "ruleset"}, "nftables"},
		{"/usr/sbin/ufw", []string{"status", "numbered"}, "ufw"},
		{"/usr/bin/firewall-cmd", []string{"--list-all"}, "firewalld"},
	} {
		out, err := runCmd(10*time.Second, a.bin, a.args...)
		if err == nil && strings.TrimSpace(out) != "" {
			return cleanLines(out), a.name
		}
	}
	return "", ""
}

func (s *firewallSource) poll(baseline bool) {
	rules, tool := snapshotRules()
	if rules == "" {
		return
	}
	s.mu.Lock()
	prev, had, prevTool := s.last, s.last != "", s.tool
	s.last, s.tool = rules, tool
	s.mu.Unlock()

	if baseline || !had || prev == rules {
		return
	}
	ev := NewEvent(model.ChangeKindFirewall, "change.firewall",
		Object{Type: "rule", Key: tool, Labels: []string{"firewall", tool}}, time.Now())
	// Agent-initiated blocks also change iptables; tagging them prevents the
	// agent's own actions from showing up as suspicious "someone changed the
	// firewall" noise.
	ev.Actor = Actor{Kind: "unknown", How: tool, Confidence: model.ConfidenceUnknown}
	if prevTool == "" {
		prevTool = tool
	}
	body, added, removed, truncated := MakeDiff(prev, rules)
	ev.Diff = &Diff{Changed: true, Body: body, Added: added, Removed: removed, Truncated: truncated}
	if added > 0 {
		ev.Object.Labels = append(ev.Object.Labels, "rule_added")
	}
	if removed > 0 {
		ev.Object.Labels = append(ev.Object.Labels, "rule_removed")
	}
	s.emit(ev)
}

var counterRe = regexp.MustCompile(`\[\d+:\d+\]`)

// stripCounters removes packet/byte counters from iptables-save output.
// Without this every read differs and the firewall looks like it changes once a
// minute forever.
func stripCounters(line string) string {
	line = counterRe.ReplaceAllString(line, "")
	return strings.TrimRight(line, " \t")
}

// stripToolComments drops the `#` preamble/epilogue the firewall tools emit.
//
// iptables-save stamps every dump with `# Generated by iptables-save v1.8.7 on
// Thu Oct 29 07:45:02 2026` and `# Completed on <time>`. Those two lines change
// on every single read, so keeping them makes the rule set look modified every
// poll (288 fake change events a day, each one burying a real one). The comments
// carry no rule state, so they are dropped wholesale.
func stripToolComments(line string) string {
	trimmed := strings.TrimSpace(line)
	if strings.HasPrefix(trimmed, "#") {
		return ""
	}
	return line
}

