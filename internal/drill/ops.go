// Deps are the panel capabilities a drill needs. Anything nil makes the
// corresponding drill unavailable instead of failing at click time.
type Deps struct {
	// FimWatches reports whether path is inside file-integrity monitoring.
	FimWatches func(path string) bool
	// FimWatch/FimUnwatch temporarily add and remove a path from monitoring.
	// Without them the sample file lands somewhere nobody is watching, and the
	// drill's conclusion flips from "the agent missed it" to "nobody looked" —
	// two very different findings that must not be confused.
	FimWatch   func(path string) error
	FimUnwatch func(path string) error
	// CronCreate/Delete/RunNow let the cron drill create a deliberately failing
	// task and run it once.
	CronCreate func(name, schedule, command string) (uint, error)
	CronDelete func(id uint) error
	CronRunNow func(id uint) error
}

// Ops returns the real fault implementations for the current host.
func Ops(deps Deps) []Op {
	return []Op{
		&cpuHogOp{},
		&logFloodOp{},
		&webshellOp{fim: deps.FimWatches, watch: deps.FimWatch, unwatch: deps.FimUnwatch},
		&cronFailOp{create: deps.CronCreate, del: deps.CronDelete, run: deps.CronRunNow},
		&diskFillOp{},
		&dockerDownOp{},
	}
}

// ---------------------------------------------------------------- CPU

const cpuUnitPrefix = "opsmini-drill-cpu-"

type cpuHogOp struct{}

func (o *cpuHogOp) Kind() Kind { return KindCPUHog }

func (o *cpuHogOp) Inject(ctx context.Context, r *Run) error {
	// One spinner per core. Half the cores was the first idea, but on a 2-core box
	// that is 50% — it never crosses the 90% threshold the drill exists to test,
	// so the operator gets a green graph and concludes "detection is broken".
	n := runtime.NumCPU()
	if n < 1 {
		n = 1
	}
	if n > 8 {
		n = 8
	}
	for i := 0; i < n; i++ {
		unit := cpuUnitPrefix + strconv.Itoa(i)
		cmd := exec.CommandContext(ctx, "systemd-run", "--unit="+unit, "--collect",
			"/bin/sh", "-c", "while :; do :; done")
		if out, err := cmd.CombinedOutput(); err != nil {
			// No systemd (container, mac): fall back to a plain child process.
			// Record the PID so restore can kill the whole group.
			pid, ferr := spawnBusyLoop()
			if ferr != nil {
				return fmt.Errorf("启动 CPU 负载失败: %v (%s)", ferr, strings.TrimSpace(string(out)))
			}
			r.PIDs = append(r.PIDs, pid)
			continue
		}
		r.Meta = ensureMeta(r.Meta)
		r.Meta["units"] = appendUnit(r.Meta["units"], unit)
	}
	r.Note = fmt.Sprintf("已用 %d 个空转进程（每核一个）占满 CPU", n)
	return nil
}

func (o *cpuHogOp) Restore(ctx context.Context, r *Run) error {
	for _, u := range splitUnits(r.Meta["units"]) {
		_ = exec.CommandContext(ctx, "systemctl", "stop", u).Run()
		_ = exec.CommandContext(ctx, "systemctl", "reset-failed", u).Run()
	}
	for _, pid := range r.PIDs {
		if pid <= 0 {
			continue
		}
		// Kill the group first: "sh -c while" spawns nothing, but a future change
		// might, and a leftover spinner is exactly the sort of thing nobody
		// notices until the CPU graph looks wrong for a week.
		_ = syscall.Kill(-pid, syscall.SIGKILL)
		_ = syscall.Kill(pid, syscall.SIGKILL)
	}
	return nil
}

func spawnBusyLoop() (int, error) {
	cmd := exec.Command("/bin/sh", "-c", "while :; do :; done")
	cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
	if err := cmd.Start(); err != nil {
		return 0, err
	}
	go func() { _ = cmd.Wait() }()
	return cmd.Process.Pid, nil
}

// ---------------------------------------------------------------- log flood

const (
	floodPath  = "/var/log/opsmini-drill-flood.log"
	floodRate  = 40 * time.Millisecond
	floodChunk = 64 << 10 // 64 KiB per write ≈ 1.6 MB/s
	floodCap   = 300 << 20
)

type logFloodOp struct {
	mu      sync.Mutex
	stopped map[string]chan struct{}
}

func (o *logFloodOp) Kind() Kind { return KindLogFlood }

func (o *logFloodOp) Inject(ctx context.Context, r *Run) error {
	if _, err := os.Stat("/var/log"); err != nil {
		return fmt.Errorf("/var/log 不可用: %w", err)
	}
	f, err := os.OpenFile(floodPath, os.O_CREATE|os.O_WRONLY|os.O_APPEND, 0o644)
	if err != nil {
		return fmt.Errorf("创建日志文件失败: %w", err)
	}
	r.Files = append(r.Files, floodPath)

	stop := make(chan struct{})
	key := string(r.Kind)
	o.mu.Lock()
	if o.stopped == nil {
		o.stopped = map[string]chan struct{}{}
	}
	o.stopped[key] = stop
	o.mu.Unlock()

	line := []byte("2026-11-10T00:00:00+08:00 ERROR opsmini-drill synthetic flood: " +
		"connection reset by peer while writing batch retry=3 — generated by a drill, safe to delete\n")
	var buf []byte
	for len(buf) < floodChunk {
		buf = append(buf, line...)
	}
	buf = buf[:floodChunk]

	go func() {
		defer f.Close()
		var written int64
		t := time.NewTicker(floodRate)
		defer t.Stop()
		for {
			select {
			case <-stop:
				return
			case <-ctx.Done():
				return
			case <-t.C:
				if written >= floodCap {
					// 到上限就停写。文件还在、还是异常，故障状态保持到自动恢复；
					// 继续写下去只会把磁盘吃掉，那不是演练，那是事故。
					return
				}
				if _, err := f.Write(buf); err != nil {
					return
				}
				written += int64(len(buf))
			}
		}
	}()
	r.Note = "约 1.6 MB/s 持续写入 " + floodPath + "，超过日志暴涨阈值后应出现事件"
	return nil
}

func (o *logFloodOp) Restore(ctx context.Context, r *Run) error {
	o.mu.Lock()
	if ch, ok := o.stopped[string(r.Kind)]; ok {
		close(ch)
		delete(o.stopped, string(r.Kind))
	}
	o.mu.Unlock()
	// Give the writer one tick to notice, then remove the file regardless.
	time.Sleep(2 * floodRate)
	removeFiles(r.Files)
	return nil
}

// ---------------------------------------------------------------- webshell

type webshellOp struct {
	fim     func(string) bool
	watch   func(string) error
	unwatch func(string) error
}

func (o *webshellOp) Kind() Kind { return KindWebshell }

const webshellDir = "/tmp/opsmini-drill-shell"

func (o *webshellOp) Inject(ctx context.Context, r *Run) error {
	if err := os.MkdirAll(webshellDir, 0o755); err != nil {
		return err
	}
	p := filepath.Join(webshellDir, "upload.php")
	r.Files = append(r.Files, webshellDir)

	// 顺序很关键：先把目录建好、把路径加进监控并重建基线（此时文件还不存在），
	// 再把样本写下去。反过来做的话，生成的基线里就包含了这个样本，Check 永远
	// 看不出「多了一个文件」——演练会显示「没被发现」，而其实是自己把证据
	// 抹掉了。
	watched := o.fim != nil && o.fim(p)
	if !watched && o.watch != nil {
		if err := o.watch(p); err != nil {
			// 加不进监控也不算失败：文件已经落地，只是这次不会有人看见。
			r.Note = "样本文件已落地，但加入文件完整性监控失败（" + err.Error() + "），本次可能不会产生事件。"
			return nil
		}
		r.Meta = ensureMeta(r.Meta)
		r.Meta["fim_added"] = "1"
		watched = true
	}
	if watched {
		r.Note = "已落地样本文件 " + p + "（已临时加入文件完整性监控），等待检出。" +
			"注意样本内容本身无害，Agent 读到后可能判定无需处置——这条演练要验证的是「有没有被发现」，不是「会不会被隔离」。"
	} else {
		r.Note = "该路径不在文件完整性监控范围内，本次不会产生事件。请先在「主机安全 → 文件完整性」把该路径加入监控再重试。"
	}

	// Deliberately inert: no code that could actually run. The point is the file
	// showing up under a monitored path.
	body := "<?php /* opsmini drill sample — not executable, safe to delete */ ?>\n"
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		return err
	}
	return nil
}

func (o *webshellOp) Restore(ctx context.Context, r *Run) error {
	removeFiles(r.Files)
	removeFiles([]string{webshellDir})
	// 演练加进去的监控项要撤掉，否则「临时」变成了永久，监控名单会被一次次演练污染。
	if r.Meta != nil && r.Meta["fim_added"] == "1" && o.unwatch != nil {
		if err := o.unwatch(webshellDir + "/upload.php"); err != nil {
			return fmt.Errorf("移除临时监控路径失败: %w", err)
		}
	}
	return nil
}

// ---------------------------------------------------------------- cron failure

type cronFailOp struct {
	create func(name, schedule, command string) (uint, error)
	del    func(uint) error
	run    func(uint) error
}

func (o *cronFailOp) Kind() Kind { return KindCronFail }

func (o *cronFailOp) Inject(ctx context.Context, r *Run) error {
	if o.create == nil || o.del == nil || o.run == nil {
		return fmt.Errorf("计划任务服务不可用")
	}
	id, err := o.create("opsmini-drill-fail", "0 3 1 1 *", "exit 1")
	if err != nil {
		return fmt.Errorf("创建演练任务失败: %w", err)
	}
	r.Meta = ensureMeta(r.Meta)
	r.Meta["job"] = strconv.FormatUint(uint64(id), 10)
	if err := o.run(id); err != nil {
		_ = o.del(id)
		delete(r.Meta, "job")
		return fmt.Errorf("立即执行演练任务失败: %w", err)
	}
	r.Note = "已创建一个必然失败的任务并执行一次，等待「计划任务失败数」检查捕获"
	return nil
}

func (o *cronFailOp) Restore(ctx context.Context, r *Run) error {
	if o.del == nil || r.Meta == nil {
		return nil
	}
	raw := r.Meta["job"]
	if raw == "" {
		return nil
	}
	id, err := strconv.ParseUint(raw, 10, 64)
	if err != nil {
		return nil
	}
	if err := o.del(uint(id)); err != nil {
		return fmt.Errorf("删除演练任务失败: %w", err)
	}
	return nil
}

// ---------------------------------------------------------------- disk fill

const (
	diskDrillPath = "/var/tmp/opsmini-drill-fill.bin"
	// 92 而不是 88：内置规则是「> 90% 持续 1 分钟」，推到 88% 根本跨不过门槛，
	// 演练会得出「磁盘告警不好用」的错误结论。
	diskTargetPct   = 92
	diskMaxAllocate = 20 << 30 // never take more than 20 GiB for a drill
)

type diskFillOp struct{}

func (o *diskFillOp) Kind() Kind { return KindDiskFill }

func (o *diskFillOp) Inject(ctx context.Context, r *Run) error {
	var st syscall.Statfs_t
	if err := syscall.Statfs("/", &st); err != nil {
		return fmt.Errorf("读取磁盘使用率失败: %w", err)
	}
	total := float64(st.Blocks) * float64(st.Bsize)
	free := float64(st.Bavail) * float64(st.Bsize)
	used := total - free
	pct := used / total * 100
	if pct >= float64(diskTargetPct) {
		return fmt.Errorf("当前已使用 %.0f%%，已达到演练目标（%d%%），未做改动", pct, diskTargetPct)
	}
	need := total*float64(diskTargetPct)/100 - used
	if need > diskMaxAllocate {
		need = diskMaxAllocate
	}
	// Keep a floor free: filling the last megabytes makes the panel itself fail to
	// write its database, which turns a drill into an outage.
	if need > free-512<<20 {
		need = free - 512<<20
	}
	if need <= 0 {
		return fmt.Errorf("剩余空间不足，无法安全演练")
	}
	size := int64(need)
	if _, err := os.Stat(filepath.Dir(diskDrillPath)); err != nil {
		return err
	}
	if out, err := exec.CommandContext(ctx, "fallocate", "-l", strconv.FormatInt(size, 10), diskDrillPath).CombinedOutput(); err != nil {
		return fmt.Errorf("分配空间失败: %v (%s)", err, strings.TrimSpace(string(out)))
	}
	r.Files = append(r.Files, diskDrillPath)
	r.Note = fmt.Sprintf("已占用 %.1f GB，磁盘使用率推高到约 %d%%", float64(size)/(1<<30), diskTargetPct)
	return nil
}

func (o *diskFillOp) Restore(ctx context.Context, r *Run) error {
	removeFiles(r.Files)
	removeFiles([]string{diskDrillPath})
	return nil
}

// ---------------------------------------------------------------- docker

type dockerDownOp struct{}

func (o *dockerDownOp) Kind() Kind { return KindDockerDown }

func (o *dockerDownOp) Inject(ctx context.Context, r *Run) error {
	if err := exec.CommandContext(ctx, "systemctl", "is-active", "docker").Run(); err != nil {
		return fmt.Errorf("docker 服务不存在或未运行，无法演练")
	}

	// socket 必须先停。
	//
	// docker.socket 处于 active 时，任何客户端连一下 /var/run/docker.sock，
	// systemd 就会把 docker.service 拉起来。而这个面板自己就在轮询容器列表——
	// 实测 stop 之后 8 秒 docker 就回来了：演练等于没做，界面还显示「docker 已停止」
	// 骗人，用户会得出「告警不灵」的结论。停掉 socket 才停得住。
	socketWasActive := exec.CommandContext(ctx, "systemctl", "is-active", "docker.socket").Run() == nil
	if socketWasActive {
		if out, err := exec.CommandContext(ctx, "systemctl", "stop", "docker.socket").CombinedOutput(); err != nil {
			return fmt.Errorf("停止 docker.socket 失败: %v (%s)", err, strings.TrimSpace(string(out)))
		}
		r.Meta = ensureMeta(r.Meta)
		r.Meta["socket_active"] = "1"
	}

	if out, err := exec.CommandContext(ctx, "systemctl", "stop", "docker").CombinedOutput(); err != nil {
		// 已经停掉的 socket 要还回去，否则这次注入失败会留下一个停用的 socket。
		if socketWasActive {
			_ = exec.CommandContext(ctx, "systemctl", "start", "docker.socket").Run()
		}
		return fmt.Errorf("停止 docker 失败: %v (%s)", err, strings.TrimSpace(string(out)))
	}
	r.Note = "docker 已停止（连同 docker.socket，否则面板轮询容器会把它激活回来）。" +
		"该机器上的容器会一并停止；恢复时只重启 docker，不会自动拉起原先的容器。"
	return nil
}

func (o *dockerDownOp) Restore(ctx context.Context, r *Run) error {
	// 先起 service 再起 socket：socket 一活，任何一次连接都会尝试激活 service，
	// 反过来做会看到一堆「connection refused」再成功，日志更难读。
	if err := exec.CommandContext(ctx, "systemctl", "start", "docker").Run(); err != nil {
		return fmt.Errorf("启动 docker 失败: %w", err)
	}
	if r.Meta != nil && r.Meta["socket_active"] == "1" {
		if err := exec.CommandContext(ctx, "systemctl", "start", "docker.socket").Run(); err != nil {
			return fmt.Errorf("启动 docker.socket 失败: %w", err)
		}
	}
	return nil
}

// ---------------------------------------------------------------- helpers

func ensureMeta(m map[string]string) map[string]string {
	if m == nil {
		return map[string]string{}
	}
	return m
}

func appendUnit(existing, unit string) string {
	if existing == "" {
		return unit
	}
	return existing + "," + unit
}

func splitUnits(s string) []string {
	if s == "" {
		return nil
	}
	return strings.Split(s, ",")
}
